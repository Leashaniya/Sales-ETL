#Run every query without indexes, then with them, and save the before/after numbers as proof that indexing helps.
from __future__ import annotations

import re
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from etl.load import get_connection  # noqa: E402

QUERIES_FILE = ROOT / "sql" / "03_analytical_queries.sql"
INDEXES_FILE = ROOT / "sql" / "02_indexes.sql"
DOCS_DIR = ROOT / "docs"
PLANS_DIR = DOCS_DIR / "query_plans"
RUNS = 5


def load_queries() -> dict[str, str]:
    """Split 03_analytical_queries.sql on '-- name: <id>' markers."""
    text = QUERIES_FILE.read_text()
    parts = re.split(r"^-- name:\s*(\w+)\s*$", text, flags=re.MULTILINE)
    queries = {}
    for name, body in zip(parts[1::2], parts[2::2]):
        sql = "\n".join(line for line in body.splitlines() if not line.strip().startswith("--")).strip()
        queries[name] = sql.rstrip(";")
    return queries


def index_names() -> list[str]:
    return re.findall(r"CREATE INDEX IF NOT EXISTS (\w+)", INDEXES_FILE.read_text())


def scan_summary(plan: dict) -> str:
    """Collect how fact_sales / the materialized view was read, e.g. 'Index Only Scan (idx_...)'."""
    found = []

    def walk(node):
        if node.get("Relation Name") in ("fact_sales", "mv_monthly_revenue") or (
            node.get("Index Name", "").startswith("idx_fact_sales")
        ):
            label = node["Node Type"]
            if node.get("Index Name"):
                label += f" ({node['Index Name']})"
            found.append(label)
        for child in node.get("Plans", []):
            walk(child)

    walk(plan["Plan"])
    return ", ".join(dict.fromkeys(found)) or "-"


def total_buffers(plan: dict) -> int:
    p = plan["Plan"]
    return int(p.get("Shared Hit Blocks", 0) + p.get("Shared Read Blocks", 0))


def run_query(cur, sql: str) -> dict:
    timings, plan = [], None
    for _ in range(RUNS):
        cur.execute(f"EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) {sql}")
        plan = cur.fetchone()[0][0]
        timings.append(plan["Execution Time"])
    cur.execute(f"EXPLAIN (ANALYZE, BUFFERS) {sql}")
    text_plan = "\n".join(row[0] for row in cur.fetchall())
    return {
        "ms": statistics.median(timings),
        "scan": scan_summary(plan),
        "pages": total_buffers(plan),
        "text_plan": text_plan,
    }


def maintenance(conn) -> None:
    conn.autocommit = True
    with conn.cursor() as cur:
        cur.execute("VACUUM (ANALYZE) retail.fact_sales")
    conn.autocommit = False


def run_all(conn, queries: dict[str, str]) -> dict[str, dict]:
    results = {}
    with conn.cursor() as cur:
        for name, sql in queries.items():
            results[name] = run_query(cur, sql)
            print(f"   {name:<32} {results[name]['ms']:>9.2f} ms   {results[name]['scan']}")
    conn.commit()
    return results


def main() -> None:
    queries = load_queries()
    indexes = index_names()
    conn = get_connection()

    with conn.cursor() as cur:
        cur.execute("SELECT count(*) FROM retail.fact_sales")
        rows = cur.fetchone()[0]
    print(f"\nfact_sales rows: {rows:,}   |   {RUNS} runs per query, median time reported\n")

    # ---- BEFORE: no performance indexes ----------------------------------------------
    print("Phase 1: WITHOUT performance indexes")
    with conn.cursor() as cur:
        for idx in indexes:
            cur.execute(f"DROP INDEX IF EXISTS retail.{idx}")
    conn.commit()
    maintenance(conn)
    before = run_all(conn, queries)

    # ---- AFTER: create indexes from 02_indexes.sql ------------------------------------
    print("\nPhase 2: WITH performance indexes")
    with conn.cursor() as cur:
        cur.execute(INDEXES_FILE.read_text())
    conn.commit()
    maintenance(conn)
    after = run_all(conn, queries)

    with conn.cursor() as cur:
        cur.execute(
            "SELECT indexrelname, pg_size_pretty(pg_relation_size(indexrelid)) "
            "FROM pg_stat_user_indexes WHERE relname = 'fact_sales' ORDER BY 1"
        )
        index_sizes = cur.fetchall()
        cur.execute("SELECT pg_size_pretty(pg_relation_size('retail.fact_sales'))")
        table_size = cur.fetchone()[0]
    conn.close()

    # ---- report -------------------------------------------------------------------------
    header = "| Query | Before (ms) | After (ms) | Speed-up | Plan before | Plan after | Pages before | Pages after |"
    lines = [
        "# Query benchmark: before vs after indexing",
        "",
        f"* `fact_sales` rows: **{rows:,}** (table size {table_size})",
        f"* Each query run {RUNS} times with `EXPLAIN (ANALYZE, BUFFERS)`; median execution time shown.",
        "* Pages = 8 KB blocks PostgreSQL had to read (lower = less I/O).",
        "* Generated by `python scripts/benchmark_queries.py`.",
        "",
        header,
        "|---|---:|---:|---:|---|---|---:|---:|",
    ]
    print("\n" + "=" * 100)
    print(f"{'Query':<32}{'Before ms':>11}{'After ms':>11}{'Speed-up':>10}   Plan after")
    print("=" * 100)
    for name in queries:
        b, a = before[name], after[name]
        speedup = b["ms"] / a["ms"] if a["ms"] else float("inf")
        print(f"{name:<32}{b['ms']:>11.2f}{a['ms']:>11.2f}{speedup:>9.1f}x   {a['scan']}")
        lines.append(
            f"| `{name}` | {b['ms']:.2f} | {a['ms']:.2f} | **{speedup:.1f}x** | {b['scan']} | {a['scan']} | {b['pages']:,} | {a['pages']:,} |"
        )
    print("=" * 100)

    q2, q2b = after.get("q2_monthly_growth"), after.get("q2b_monthly_growth_from_mv")
    if q2 and q2b:
        msg = (f"Q2 full-table aggregation: {q2['ms']:.1f} ms on fact_sales vs {q2b['ms']:.2f} ms on the "
               f"materialized view ({q2['ms'] / q2b['ms']:.0f}x faster) - indexes can't help a full scan, pre-aggregation can.")
        print(msg)
        lines += ["", f"**Materialized view:** {msg}"]

    lines += ["", "## Index sizes", "", "| Index | Size |", "|---|---:|"]
    lines += [f"| `{n}` | {s} |" for n, s in index_sizes]

    DOCS_DIR.mkdir(exist_ok=True)
    PLANS_DIR.mkdir(exist_ok=True)
    (DOCS_DIR / "benchmark_results.md").write_text("\n".join(lines) + "\n")
    for name in queries:
        (PLANS_DIR / f"{name}.txt").write_text(
            f"=== {name} : BEFORE (no indexes) ===\n{before[name]['text_plan']}\n\n"
            f"=== {name} : AFTER (with indexes) ===\n{after[name]['text_plan']}\n"
        )
    print("\nSaved docs/benchmark_results.md and docs/query_plans/*.txt")


if __name__ == "__main__":
    main()
